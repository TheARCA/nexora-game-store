export const gamePrice = (game) =>
  Math.round(game.price * (1 - game.discount / 100));
export const rupiah = (value, language = "id") =>
  new Intl.NumberFormat(language === "en" ? "en-US" : "id-ID", {
    style: "currency",
    currency: "IDR",
    currencyDisplay: "narrowSymbol",
    maximumFractionDigits: 0,
  }).format(value);
export const gameImage = (game) =>
  game.image || `${import.meta.env.BASE_URL}games/${game.id}.jpg`;
